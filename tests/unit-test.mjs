// Run (optional): node tests/unit-test.mjs
import assert from 'node:assert/strict';
import { EventBus } from '../js/core/event-bus.js';
import { Project } from '../js/core/project.js';
import { History } from '../js/core/history.js';
import { serialize, parse } from '../js/core/project-serializer.js';
import { createBlock } from '../js/models/block.js';
import { checkValue, N } from '../js/models/schema.js';
import { createRoad, chainage, roadStats, fmtStation } from '../js/models/road.js';
import { createNode, createPipe, pipeLength } from '../js/models/pipe.js';
import { collectWarnings } from '../js/models/registry.js';
const bus = new EventBus(), p = new Project(bus), h = new History(p, bus);
h.record(); p.add(createBlock(p.newId(), 1, 2)); assert.equal(p.objects.length, 1);
h.record(); p.update('OBJ-0001', { x: 5 });
h.undo(); assert.equal(p.get('OBJ-0001').x, 1); h.redo(); assert.equal(p.get('OBJ-0001').x, 5);
h.undo(); h.undo(); assert.equal(p.objects.length, 0);
h.redo(); h.redo();
const back = parse(serialize(p)); assert.equal(back.objects[0].x, 5); assert.equal(back.nextId, 2);
assert.throws(() => parse('{bad'), /not valid JSON/);
assert.throws(() => parse('{"format":"x"}'), /not an EVLab/);
assert.throws(() => parse(JSON.stringify({ format: 'evlab-infra-project', schema: 1, objects: [{ type: 'tunnel' }] })), /unsupported type/);
const bad = JSON.parse(serialize(p)); bad.objects[0].width = -1;
assert.throws(() => parse(JSON.stringify(bad)), /Width/);
assert.ok(checkValue(N('x', 'X', -1, 1), NaN)); assert.equal(checkValue(N('x', 'X', -1, 1), 0.5), null);
// Roads and pipes
const rd = createRoad('R', [{ x: 0, y: 0, z: 0 }, { x: 30, y: 40, z: 10 }]);
assert.deepEqual(chainage(rd.points), [0, 50]); assert.equal(Math.round(roadStats(rd.points).maxGradePct), 20);
assert.equal(roadStats(rd.points).len3d.toFixed(3), Math.hypot(50, 10).toFixed(3)); assert.equal(fmtStation(1234.4), '1+234');
const q = new Project(bus); q.add(rd); const a = q.add(createNode('OBJ-0001', 'Junction', 0, 0)), b = q.add(createNode('OBJ-0002', 'Valve', 30, 40));
a.invert = 0; b.invert = 0; const pp = q.add(createPipe('OBJ-0003', a.id, b.id)); q.nextId = 4;
assert.equal(pipeLength(pp, q).len3d, 50); assert.ok(collectWarnings(q).some(w => /material unspecified/.test(w.msg)));
const rt = parse(serialize(q)); assert.equal(rt.objects.length, 4);
const broken = JSON.parse(serialize(q)); broken.objects.splice(1, 1); assert.throws(() => parse(JSON.stringify(broken)), /missing node/);
q.remove(a.id); assert.equal(q.objects.some(o => o.type === 'pipe'), false);
// Structures and crossings
import { createBridge } from '../js/models/bridge.js';
import { createCulvert } from '../js/models/culvert.js';
import { createWatercourse } from '../js/models/watercourse.js';
import { findCrossings } from '../js/models/crossings.js';
const c = new Project(bus);
c.add(createRoad('OBJ-0001', [{ x: -10, y: 10, z: 5 }, { x: 50, y: 10, z: 5 }]));
c.add(createWatercourse('OBJ-0002', [{ x: 20, y: -10, z: 0 }, { x: 20, y: 40, z: 0 }]));
const n1 = c.add(createNode('OBJ-0003', 'Junction', 10, 0)), n2 = c.add(createNode('OBJ-0004', 'Junction', 10, 30)); n1.invert = -2; n2.invert = -2;
c.add(createPipe('OBJ-0005', n1.id, n2.id)); c.add(createBridge('OBJ-0006', 22, 10)); c.add(createCulvert('OBJ-0007', 40, 40)); c.nextId = 8;
let x = findCrossings(c); assert.equal(x.length, 2);
const pr = x.find(r => r.kind === 'pipe × road'); assert.equal(pr.gap.toFixed(2), '6.50'); assert.ok(/No clearance/.test(pr.status));
assert.ok(/bridge OBJ-0006/.test(x.find(r => r.kind === 'road × watercourse').status));
c.meta.crossing.minClearance = 7; assert.ok(/Below/.test(findCrossings(c).find(r => r.kind === 'pipe × road').status));
const rc = parse(serialize(c)); assert.equal(rc.objects.length, 7); assert.equal(rc.meta.crossing.minClearance, 7);
const bb = JSON.parse(serialize(c)); bb.objects[5].pierCount = 1.5; assert.throws(() => parse(JSON.stringify(bb)), /whole number/);
// Milestone 5: CSV, quantities, GeoJSON, DXF, report
import { parseCsv, toCsv, inventoryRows, importAssets } from '../js/io/csv-io.js';
import { quantities, quantityCsv } from '../js/reports/quantity-report.js';
import { toGeoJSON, fromGeoJSON } from '../js/io/geojson-io.js';
import { toDxf } from '../js/io/dxf-export.js';
import { projectReportHtml } from '../js/reports/project-report.js';
assert.deepEqual(parseCsv(toCsv([['a', 'b,c', 'd"e'], ['1', '', '3']])), [['a', 'b,c', 'd"e'], ['1', '', '3']]);
assert.throws(() => parseCsv('a,"b'), /unterminated/);
assert.equal(inventoryRows(c).length, 8);
const ir = importAssets(c, 'id,name,material,diameter_mm,asset_id\nOBJ-0005,Main A,HDPE,315,P-1\nOBJ-9999,x,,,\nOBJ-0005,,,abc,\nOBJ-0003,Node,Steel,,N-1');
assert.equal(ir.patches.length, 2); assert.equal(ir.patches[0].patch.diameter, 315); assert.equal(ir.errors.length, 2); assert.equal(ir.ignored.length, 1);
assert.throws(() => importAssets(c, 'name\nx'), /"id" column/);
const qr = quantities(c); const rs = qr.sections.find(x => x.title === 'Roads'); assert.equal(rs.rows[0][7], 420); assert.equal(rs.rows[0][8], 126);
assert.ok(quantityCsv(qr).includes('Calculation assumptions'));
const gl = toGeoJSON(c, { mode: 'local' }); assert.equal(gl.geojson.features.length, 7); assert.ok(gl.geojson.crs);
const gback = fromGeoJSON(JSON.stringify(gl.geojson), { mode: 'local', lineAs: 'road', newId: (() => { let i = 0; return () => 'L' + i++; })() }); assert.equal(gback.objects.length, 7); assert.equal(gback.skipped.length, 0);
const org = { lon: 90.4, lat: 23.8 }, gg = toGeoJSON(c, { mode: 'geographic', origin: org });
const rt2 = fromGeoJSON(JSON.stringify(gg.geojson), { mode: 'geographic', origin: org, lineAs: 'road', newId: (() => { let i = 0; return () => 'Y' + i++; })() });
const nn = rt2.objects.find(o => o.type === 'node'); assert.ok(Math.abs(nn.x - 10) < 0.01 && Math.abs(nn.y - 0) < 0.01);
assert.throws(() => toGeoJSON(c, { mode: 'geographic', origin: { lon: 999, lat: 0 } }), /origin/);
const poly = fromGeoJSON(JSON.stringify({ type: 'FeatureCollection', features: [{ type: 'Feature', properties: {}, geometry: { type: 'Polygon', coordinates: [] } }] }), { mode: 'local', lineAs: 'road', newId: () => 'Z' });
assert.equal(poly.objects.length, 0); assert.equal(poly.skipped.length, 1);
const dx = toDxf(c); assert.ok(dx.text.includes('ENTITIES') && dx.counts.PIPE === 1 && dx.counts.ROAD_EDGE === 2 && dx.text.trimEnd().endsWith('EOF'));
c.objects[0].name = '<script>x</script>'; assert.ok(!projectReportHtml(c).includes('<script>x'));
// Milestone 6: coordinates, geographic origin, extra validation
import { toGeo, fromGeo } from '../js/core/coordinates.js';
const o6 = { lon: 90.4, lat: 23.8 }, [lo6, la6] = toGeo(100, 200, o6), [x6, y6] = fromGeo(lo6, la6, o6);
assert.ok(Math.abs(x6 - 100) < 1e-6 && Math.abs(y6 - 200) < 1e-6); assert.ok(la6 > o6.lat && lo6 > o6.lon);
assert.ok(Math.abs((la6 - o6.lat) * 111000 - 200) < 2);
const gp = new Project(bus); gp.meta.geo = { originLon: 90.4, originLat: 23.8 };
assert.equal(parse(serialize(gp)).meta.geo.originLat, 23.8);
const badGeo = JSON.parse(serialize(gp)); badGeo.meta.geo.originLat = 123; assert.throws(() => parse(JSON.stringify(badGeo)), /origin/);
const wp = new Project(bus); wp.add(createNode('OBJ-0001', 'Junction', 0, 0)); const w2 = wp.add(createNode('OBJ-0002', 'Junction', 5, 5)); w2.assetId = 'A'; wp.get('OBJ-0001').assetId = 'A';
wp.add(createRoad('OBJ-0003', [{ x: 0, y: 0, z: 0 }, { x: 0, y: 0, z: 0 }, { x: 10, y: 0, z: 5 }]));
const msgs = collectWarnings(wp).map(x => x.msg).join('|'); assert.ok(/no connected pipes/.test(msgs) && /used by 2 objects/.test(msgs) && /duplicate consecutive/.test(msgs) && /exceeds 12%/.test(msgs));
console.log('All unit tests passed');
